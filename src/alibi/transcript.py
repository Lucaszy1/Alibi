"""Parsing of Claude Code session transcripts.

A transcript is a JSONL file under ``~/.claude/projects/<project>/<session-id>.jsonl``.
Each line is one record. Only three shapes carry timeline meaning:

- ``type: "user"`` with ``message.content`` as a plain string: a prompt from the human.
- ``type: "assistant"`` with ``tool_use`` blocks in ``message.content``: tool calls.
- ``type: "user"`` with ``tool_result`` blocks in ``message.content``: tool results.

Everything else (attachments, api-request records, mode changes, titles, file-history
snapshots, ...) is ignored.
"""

from __future__ import annotations

import bisect
import json
from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from pathlib import Path
from typing import Any, Iterable, Union


class SourceKind(str, Enum):
    TRUSTED = "TRUSTED"
    UNTRUSTED = "UNTRUSTED"


# Tools whose results are generated by the harness itself (confirmations, not outside
# content). Every other tool, including unknown ones, is treated as UNTRUSTED so that a
# new or unrecognised tool can never quietly launder external content.
TRUSTED_RESULT_TOOLS = frozenset(
    {
        "Write",
        "Edit",
        "MultiEdit",
        "NotebookEdit",
        "TodoWrite",
        "AskUserQuestion",
        "EnterPlanMode",
        "ExitPlanMode",
        "ScheduleWakeup",
        "ToolSearch",
    }
)


@dataclass(frozen=True)
class UserPrompt:
    timestamp: datetime
    text: str


@dataclass(frozen=True)
class ToolCall:
    timestamp: datetime
    tool_use_id: str
    tool_name: str
    tool_input: dict[str, Any] = field(hash=False)
    # Working directory the agent was running in when it made the call.
    cwd: str | None = field(default=None, compare=False)


@dataclass(frozen=True)
class ToolResult:
    timestamp: datetime
    tool_use_id: str
    content: str
    source_kind: SourceKind


Event = Union[UserPrompt, ToolCall, ToolResult]


def classify_source(tool_name: str | None) -> SourceKind:
    """Trust level of a tool's result, based on the tool that produced it."""
    if tool_name in TRUSTED_RESULT_TOOLS:
        return SourceKind.TRUSTED
    return SourceKind.UNTRUSTED


def _parse_timestamp(value: str) -> datetime:
    # Transcripts use ISO 8601 with a trailing "Z"; fromisoformat accepts it from 3.11.
    return datetime.fromisoformat(value)


def _flatten_content(content: Any) -> str:
    """Tool result content is either a string or a list of content blocks."""
    if content is None:
        return ""
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        parts = []
        for block in content:
            if isinstance(block, dict):
                if block.get("type") == "text":
                    parts.append(block.get("text", ""))
                else:
                    parts.append(f"[{block.get('type', 'unknown')} block]")
            else:
                parts.append(str(block))
        return "\n".join(parts)
    return str(content)


def _is_human_prompt(record: dict[str, Any]) -> bool:
    if record.get("isMeta") or record.get("isSidechain"):
        # Sidechain "prompts" are written by a parent agent to a subagent, not by the human.
        return False
    origin = record.get("origin")
    if isinstance(origin, dict) and origin.get("kind") not in (None, "human"):
        return False
    return isinstance(record.get("message", {}).get("content"), str)


MAX_TRANSCRIPT_BYTES = 100 * 1024 * 1024


def _read_records(path: Path) -> Iterable[dict[str, Any]]:
    if path.stat().st_size > MAX_TRANSCRIPT_BYTES:
        raise ValueError(f"transcript too large: {path.stat().st_size} bytes exceeds {MAX_TRANSCRIPT_BYTES}")
    with path.open(encoding="utf-8") as f:
        lines = f.readlines()
    for i, line in enumerate(lines):
        line = line.strip()
        if not line:
            continue
        try:
            yield json.loads(line)
        except json.JSONDecodeError:
            # A live session may be mid-write; tolerate only a truncated final line.
            if i == len(lines) - 1:
                return
            raise


_TOOL_ALIASES = {
    "shell": "Bash", "bash": "Bash", "sh": "Bash", "terminal": "Bash", "run": "Bash",
    "powershell": "PowerShell", "pwsh": "PowerShell",
    "write": "Write", "write_file": "Write", "create_file": "Write",
    "edit": "Edit", "edit_file": "Edit", "str_replace": "Edit",
    "read": "Read", "read_file": "Read", "cat": "Read",
}


def _canon_tool(name: str) -> str:
    return _TOOL_ALIASES.get(name.strip().lower(), name)


def _looks_generic(record: dict) -> bool:
    """A neutral cross-agent record is keyed by role/kind, not by Claude Code's ``type``."""
    return "type" not in record and ("role" in record or "kind" in record)


def _parse_generic(records) -> list[Event]:
    """Parse a neutral cross-agent JSONL transcript so any agent can feed Alibi.

    One JSON object per line: a prompt ``{ts, role:"user", text}``, a tool call
    ``{ts, role:"assistant", tool, id, input}``, or a result ``{ts, role:"tool", id, output,
    trusted?}``. ``trusted`` defaults to false, so unrecognized content is treated as untrusted.
    """
    events: list[Event] = []
    for r in records:
        role = (r.get("role") or r.get("kind") or "").lower()
        raw_ts = r.get("ts") or r.get("timestamp")
        if not raw_ts:
            continue
        ts = _parse_timestamp(raw_ts)
        if role in ("user", "human") and isinstance(r.get("text") or r.get("content"), str):
            events.append(UserPrompt(ts, r.get("text") or r.get("content")))
        elif (r.get("tool") or r.get("tool_name")) and role in ("assistant", "agent", "tool_call", "action"):
            name = _canon_tool(str(r.get("tool") or r.get("tool_name")))
            tid = str(r.get("id") or r.get("tool_use_id") or len(events))
            events.append(ToolCall(ts, tid, name, r.get("input") or r.get("args") or {}, r.get("cwd")))
        elif role in ("tool", "tool_result", "observation", "result"):
            tid = str(r.get("id") or r.get("tool_use_id") or "")
            trusted = bool(r.get("trusted", False))
            content = _flatten_content(r.get("output") if r.get("output") is not None else r.get("content"))
            events.append(ToolResult(ts, tid, content, SourceKind.TRUSTED if trusted else SourceKind.UNTRUSTED))
    events.sort(key=lambda e: e.timestamp)
    return events


def load_transcript(path: str | Path) -> list[Event]:
    """Parse a transcript into UserPrompt / ToolCall / ToolResult events, ordered by time.

    Auto-detects the format: Claude Code's own JSONL (records keyed by ``type``), or a neutral
    cross-agent JSONL (records keyed by ``role``/``kind``) so any agent can feed Alibi.
    """
    records = list(_read_records(Path(path)))
    if records and _looks_generic(records[0]):
        return _parse_generic(records)

    events: list[Event] = []
    tool_names: dict[str, str] = {}

    for record in records:
        kind = record.get("type")
        if kind not in ("user", "assistant") or "timestamp" not in record:
            continue
        ts = _parse_timestamp(record["timestamp"])
        content = record.get("message", {}).get("content")

        if kind == "user" and _is_human_prompt(record):
            events.append(UserPrompt(ts, content))
            continue

        if not isinstance(content, list):
            continue
        for block in content:
            if not isinstance(block, dict):
                continue
            if kind == "assistant" and block.get("type") == "tool_use":
                tool_names[block["id"]] = block["name"]
                events.append(
                    ToolCall(ts, block["id"], block["name"], block.get("input") or {}, record.get("cwd"))
                )
            elif kind == "user" and block.get("type") == "tool_result":
                tool_use_id = block["tool_use_id"]
                events.append(
                    ToolResult(
                        ts,
                        tool_use_id,
                        _flatten_content(block.get("content")),
                        classify_source(tool_names.get(tool_use_id)),
                    )
                )

    # Stable sort: events sharing a timestamp keep their file order.
    events.sort(key=lambda e: e.timestamp)
    return events


def events_before(events: list[Event], timestamp: datetime, limit: int | None = None) -> list[Event]:
    """Events strictly before ``timestamp``, oldest first; at most the last ``limit`` of them.

    ``events`` must be sorted by timestamp, as returned by ``load_transcript``.
    """
    end = bisect.bisect_left([e.timestamp for e in events], timestamp)
    start = 0 if limit is None else max(0, end - limit)
    return events[start:end]


def last_prompt_before(events: list[Event], timestamp: datetime) -> UserPrompt | None:
    """The most recent thing the human typed before ``timestamp``."""
    for event in reversed(events_before(events, timestamp)):
        if isinstance(event, UserPrompt):
            return event
    return None
